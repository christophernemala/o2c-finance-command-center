import { test } from "node:test";
import assert from "node:assert/strict";
import { migratedDatabase } from "./pg-helper";
import { deliverApproved } from "../src/lib/collections/send";
import type { SqlPool } from "../src/lib/postgres/transaction";
const id = (n: number) => `00000000-0000-4000-8000-${String(n).padStart(12, "0")}`;

test("messaging consent, approval, configured-channel claims and no automatic phone retries", async () => {
  const db = await migratedDatabase();
  const T = id(10), E = id(20), C = id(30), K = id(60);
  try {
    await db.query("insert into auth.users(id,email_confirmed_at) values($1,now()),($2,now())", [id(1), id(2)]);
    await db.query("insert into public.tenants(id,name) values($1,'Tenant')", [T]);
    await db.query("insert into public.memberships values($1,$2,'maker'),($1,$3,'approver')", [T, id(1), id(2)]);
    await db.query("insert into public.entities(id,tenant_id,name) values($1,$2,'Entity')", [E, T]);
    await db.query("insert into public.customers(id,tenant_id,entity_id,account,name) values($1,$2,$3,'C1','Customer')", [C, T, E]);
    await db.query("insert into public.invoices(id,tenant_id,entity_id,customer_id,number,issued_at,due_date,gross,dispute) values($1,$2,$3,$4,'INV-1',current_date-100,current_date-70,1200.50,'none')", [id(40), T, E, C]);
    async function user(n: number) {
      await db.exec("reset role");
      const hash = String(n).padStart(64, "0");
      await db.query("insert into auth.sessions(token_hash,user_id,purpose,aal,expires_at) values($1,$2,'login','aal1',now()+interval '1 hour') on conflict do nothing", [hash, id(n)]);
      await db.query("select set_config('o2c.session_hash',$1,false)", [hash]);
      await db.exec("set role authenticated");
    }
    await user(1);
    const contact = (phone: string, sms: boolean, wa: boolean, note: string | null) => db.query("select public.add_customer_contact($1,$2,$3,$4,'Reem','ar@example.com','ar',true,$5,$6,$7,$8)", [T, E, K, C, phone, sms, wa, note]);
    await assert.rejects(contact("0501234567", true, false, "Written request"), /Invalid phone/);
    await assert.rejects(contact("+971501234567", true, false, null), /consent/i);
    await contact("+971501234567", true, false, "Customer request dated 16 October");
    const propose = (n: number, channel: string, attach = false) => db.query("select public.propose_collection_message($1,$2,$3,$4,$5,'firm','Payment reminder','Please pay the approved overdue invoice.',$6,$7,$8)", [T, E, id(n), C, K, [id(40)], attach, channel]);
    await assert.rejects(propose(70, "whatsapp"), /consent/i);
    await assert.rejects(propose(70, "sms", true), /attachment/i);
    await propose(70, "sms");
    await assert.rejects(propose(70, "email"), /Idempotency/);
    await assert.rejects(db.query("select public.decide_collection_message($1,$2,$3,'approved')", [T, E, id(70)]), /Forbidden|Independent/);
    await db.exec("reset role; set role o2c_app");
    const claim = async (channels: string[]) => (await db.query<{ v: { id: string; channel: string; to: string; attempts: number }[] }>("select o2c_private.claim_collection_messages(5,$1::text[]) as v", [channels])).rows[0].v;
    assert.deepEqual(await claim(["sms"]), [], "pending is never sent");
    await user(2);
    await db.query("select public.decide_collection_message($1,$2,$3,'approved')", [T, E, id(70)]);
    await db.exec("reset role");
    const approvalAudit = (await db.query<{ detail: { to: string; channel: string } }>("select detail from public.audit_events where record_id=$1 and operation='collection_message.approved'", [id(70)])).rows[0].detail;
    assert.deepEqual([approvalAudit.channel, approvalAudit.to], ["sms", "+971501234567"]);
    await db.exec("set role o2c_app");
    assert.deepEqual(await claim(["email"]), [], "unconfigured channels stay approved");
    const rows = await claim(["sms"]);
    assert.deepEqual(rows.map(m => [m.id, m.channel, m.to, m.attempts]), [[id(70), "sms", "+971501234567", 1]]);
    await db.query("select o2c_private.complete_collection_message($1,1,false,null,'Outcome unknown; reconcile with Twilio before proposing again')", [id(70)]);
    assert.deepEqual(await claim(["sms"]), [], "phone failure is never retried automatically");
    await db.exec("reset role");
    assert.equal((await db.query<{ status: string }>("select status from public.collection_messages where id=$1", [id(70)])).rows[0].status, "failed");
    await user(1);
    await propose(71, "sms");
    await user(2);
    await db.query("select public.decide_collection_message($1,$2,$3,'approved')", [T, E, id(71)]);
    await db.exec("reset role; set role o2c_app");
    await claim(["sms"]);
    await db.exec("reset role");
    await db.query("update public.collection_messages set sending_at=now()-interval '20 minutes' where id=$1", [id(71)]);
    await db.exec("set role o2c_app");
    assert.deepEqual(await claim(["sms"]), [], "a crashed worker is not retried for phone channels");
    await db.exec("reset role");
    assert.match((await db.query<{ error: string }>("select error from public.collection_messages where id=$1", [id(71)])).rows[0].error, /unknown|reconcile/i);
    await user(1);
    await propose(72, "sms");
    await db.query("select public.archive_customer_contact($1,$2,$3)", [T, E, K]);
    await user(2);
    await assert.rejects(db.query("select public.decide_collection_message($1,$2,$3,'approved')", [T, E, id(72)]), /pending|Stale/);
    await user(1);
    await db.query("select public.add_customer_contact($1,$2,$3,$4,'Reem','ar@example.com','ar',true,'+971501234568',false,true,'Written WhatsApp permission')", [T, E, id(61), C]);
    const proposeWa = (n: number) => db.query("select public.propose_collection_message($1,$2,$3,$4,$5,'firm','Payment reminder','Please pay the approved overdue invoice.',$6,false,'whatsapp')", [T, E, id(n), C, id(61), [id(40)]]);
    await assert.rejects(db.query("select public.propose_collection_message($1,$2,$3,$4,$5,'firm','Payment reminder','Please pay the approved overdue invoice.',$6,false,'sms')", [T, id(21), id(73), C, id(61), [id(40)]]), /Forbidden/);
    await proposeWa(73);
    const account = (await db.query<{ v: { contacts: { phone: string }[]; messages: { channel: string; to: string }[] } }>("select public.customer_account($1,$2,$3,current_date) as v", [T, E, C])).rows[0].v;
    assert.equal(account.contacts[0].phone, "+971501234568");
    assert.deepEqual([account.messages[0].channel, account.messages[0].to], ["whatsapp", "+971501234568"]);
    await user(2);
    await db.query("select public.decide_collection_message($1,$2,$3,'approved')", [T, E, id(73)]);
    await db.exec("reset role; create role messaging_runtime login nosuperuser nobypassrls; grant o2c_app to messaging_runtime");
    const pool: SqlPool = { connect: async () => {
      await db.exec("reset role; set role messaging_runtime");
      return { query: (sql: string, values?: unknown[]) => db.query(sql, values) as never, release: () => {} };
    } };
    const calls: string[] = [];
    const senders = { whatsapp: async (message: { to: string; text: string }, key: string) => {
      calls.push(key); assert.equal(message.to, "+971501234568"); assert.equal(message.text, "Please pay the approved overdue invoice.");
      return { ok: true as const, id: `SM${"b".repeat(32)}` };
    } };
    assert.deepEqual(await deliverApproved(pool, { email: null, sms: null }), { claimed: 0, sent: 0, failed: 0, configured: false });
    assert.deepEqual(await deliverApproved(pool, senders), { claimed: 1, sent: 1, failed: 0, configured: true });
    await deliverApproved(pool, senders);
    assert.deepEqual(calls, [id(73)], "a completed message is not dispatched twice");
    await db.exec("reset role");
    assert.deepEqual((await db.query("select status,provider_id from public.collection_messages where id=$1", [id(73)])).rows[0], { status: "sent", provider_id: `SM${"b".repeat(32)}` });
    await user(1);
    await proposeWa(74);
    await user(2);
    await db.query("select public.decide_collection_message($1,$2,$3,'approved')", [T, E, id(74)]);
    await db.exec("reset role");
    await db.query("update public.customer_contacts set whatsapp_opt_in=false where id=$1", [id(61)]);
    assert.deepEqual(await deliverApproved(pool, senders), { claimed: 0, sent: 0, failed: 0, configured: true });
    assert.deepEqual(calls, [id(73)], "withdrawn consent is rechecked before dispatch");
  } finally { await db.close(); }
});
